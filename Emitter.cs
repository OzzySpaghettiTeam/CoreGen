	/// <summary>The type at the end of a dotted member path, and whether the fill can assign it directly (else by reflection).</summary>
	private (ITypeSymbol, bool) ResolveMember(INamedTypeSymbol type, string path)
	{
		ITypeSymbol cur = type;
		bool accessible = true;
		string[] segments = path.Split('.');
		for (int i = 0; i < segments.Length; i++)
		{
			IFieldSymbol f = Model.FindField(cur, segments[i]) ?? throw new CoreGenException($"{type.ToDisplayString()} has no field '{segments[i]}' for '{path}' (vanilla {current.Script.Vanilla.Info.FullName})");
			if (f.IsReadOnly && i == segments.Length - 1)
			{
				throw new CoreGenException($"{type.ToDisplayString()}.{path} is readonly");
			}
			accessible &= model.Accessible(f, type);
			cur = f.Type;
		}
		if (!accessible && segments.Length > 1)
		{
			throw new CoreGenException($"{type.ToDisplayString()}.{path}: a member on the way is not accessible from {type.Name}; make it internal or map the field elsewhere");
		}
		return (cur, accessible);
	}

