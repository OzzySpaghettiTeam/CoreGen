	/// <summary>A reference in a fill; a rebuilt component of this scope created later is assigned in the link method.</summary>
	private string? Reference(AssetTypeValueField v, string lvalue)
	{
		long pathId = v["m_PathID"].AsLong;
		GameObj? target = Files.Get(current.Obj.File, v);
		if (target == null)
		{
			return pathId == 0 ? "null" : throw new CoreGenException($"{lvalue}: reference into a file CoreGen did not load ({current.Obj})");
		}
		if (target.Id == current.Obj.Id)
		{
			return "c";
		}
		string expr = ObjectExpr(target, lvalue);
		if (planner!.Rebuilt.TryGetValue(target.Id, out RebuiltInstance? r) && r.Scope == scope && !created.Contains(target.Id))
		{
			link.Add($"{lvalue} = {expr};");
			return null;
		}
		return expr;
	}

	/// <summary>The type generated code sees an object as.</summary>
	private ITypeSymbol ObjectType(GameObj o)
	{
		if (planner!.PlanOf(o) is { Type: { } t })
		{
			return t;
		}
		string name = o.Script != null ? o.Script.FullName : GameFiles.EngineTypeName(o.ClassId);
		return model.Compilation.GetTypeByMetadataName(name) ?? throw new CoreGenException($"type {name} of {o} is not available to the project");
	}

	private string ComponentTypeName(GameObj o) => planner!.PlanOf(o) is { Type: { } t } ? TypeName(t) : "global::" + (o.Script != null ? o.Script.FullName : GameFiles.EngineTypeName(o.ClassId));

	/// <summary>An expression for an object generated code can reach: scope hierarchy, Resources prefab, or an asset with a unique name.</summary>
	private string ObjectExpr(GameObj target, string? lvalue)
	{
		if (planner!.PlanOf(target) is { Fate: ScriptFate.Dropped or ScriptFate.Broken } dead)
		{
			return $"null /* {dead.Vanilla.Info.FullName} is {(dead.Fate == ScriptFate.Dropped ? "dropped" : "broken")} */";
		}
		bool inHierarchy = target.ClassId == GameFiles.ClassGameObject || target.IsComponent;
		if (inHierarchy)
		{
			GameObj go = target.ClassId == GameFiles.ClassGameObject ? target : Files.Get(target.GameObject!.Value)!;
			Scope? owner = target.File.IsScene ? (target.File == scope.File ? scope : null) : PrefabScope(target);
			string hierarchy;
			if (owner == scope)
			{
				hierarchy = "s";
			}
			else if (owner?.PrefabRoot != null)
			{
				hierarchy = $"{Rt}Hierarchy.Prefab({Str(owner.ResourcePath!)})";
			}
			else
			{
				throw new CoreGenException($"{lvalue ?? target.ToString()}: points into another scene or an unloadable prefab ({target})");
			}
			string path = string.Join(", ", planner.PathOf(go, owner!).Select(Str));
			if (target.ClassId == GameFiles.ClassGameObject)
			{
				return $"{hierarchy}.Go({path})";
			}
			int k = 0;
			foreach (ObjId c in go.Components)
			{
				if (c == target.Id)
				{
					break;
				}
				if (Files.Get(c) is { } other && other.ClassId == target.ClassId && other.Script == target.Script)
				{
					k++;
				}
			}
			return $"{hierarchy}.Get<{ComponentTypeName(target)}>({k}{(path.Length > 0 ? ", " + path : "")})";
		}
		if (Files.ResourcePaths.TryGetValue(target.Id, out List<string>? paths))
		{
			return $"global::UnityEngine.Resources.Load<{ComponentTypeName(target)}>({Str(paths[0])})";
		}
		List<GameObj> same = Files.Files.Values.Where(f => !f.IsScene).SelectMany(f => f.Objects.Values).Where(o => o.ClassId == target.ClassId && o.Script == target.Script && o.Name == target.Name).ToList();
		if (target.Name.Length > 0 && same.Count == 1)
		{
			return $"{Rt}Assets.Find<{ComponentTypeName(target)}>({Str(target.Name)})";
		}
		if (target.SpriteRect is var (x, y, w, h))
		{
			// Sprites sharing a name differ in size, else in position on their texture.
			if (same.Count(o => o.SpriteRect?.w == w && o.SpriteRect?.h == h) == 1)
			{
				return $"{Rt}Assets.Sprite({Str(target.Name)}, {Float(w)}, {Float(h)})";
			}
			if (same.Count(o => o.SpriteRect == target.SpriteRect) == 1)
			{
				return $"{Rt}Assets.Sprite({Str(target.Name)}, {Float(w)}, {Float(h)}, {Float(x)}, {Float(y)})";
			}
		}
		if (target.Mixer is ObjId mixerId && Files.Get(mixerId) is { } mixer && same.Count(o => o.Mixer == target.Mixer) == 1
			&& Files.Files.Values.SelectMany(f => f.Objects.Values).Count(o => o.ClassId == mixer.ClassId && o.Name == mixer.Name) == 1)
		{
			return $"{Rt}Assets.MixerGroup({Str(mixer.Name)}, {Str(target.Name)})";
		}
		throw new CoreGenException($"{lvalue ?? target.ToString()}: asset {target} is not under Resources and its name is not unique among its type ({same.Count})");
	}

	private Scope? PrefabScope(GameObj target)
	{
		GameObj? root = planner!.Data.RootOf(target);
		if (root == null || !Files.ResourcePaths.TryGetValue(root.Id, out List<string>? paths))
		{
			return null;
		}
		return planner.Scopes.FirstOrDefault(s => s.PrefabRoot?.Id == root.Id) ?? new Scope { File = target.File, PrefabRoot = root, ResourcePath = paths[0] };
	}

	private string GoExpr(GameObj go) => $"s.Go({string.Join(", ", planner!.PathOf(go, scope).Select(Str))})";

	public static string TypeName(ITypeSymbol t) => t.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

	public static string Identifier(string s)
	{
		StringBuilder b = new();
		foreach (char c in s)
		{
			b.Append(char.IsLetterOrDigit(c) ? c : '_');
		}
		return b.ToString();
	}

	/// <summary>Indented lines of C#.</summary>
	private sealed class Code
	{
		private readonly StringBuilder sb = new();
		public int Indent;

		public void Line(string s)
		{
			if (s.Length > 0)
			{
				sb.Append('\t', Indent);
			}
			sb.Append(s).Append('\n');
		}

		public void Open()
		{
			Line("{");
			Indent++;
		}

		public void Close()
		{
			Indent--;
			Line("}");
		}

		public string Indented(int by)
		{
			StringBuilder r = new();
			foreach (string l in sb.ToString().Split('\n'))
			{
				if (l.Length > 0)
				{
					r.Append('\t', by).Append(l);
				}
				r.Append('\n');
			}
			return r.ToString().TrimEnd('\n') + "\n";
		}
	}
