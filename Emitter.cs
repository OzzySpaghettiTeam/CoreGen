using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using AssetsTools.NET;
using Microsoft.CodeAnalysis;

namespace CoreGen;

/// <summary>
/// Writes the generated source: per scene and per Resources prefab, the calls that recreate rebuilt components and
/// restore the references and UnityEvent calls other components held to them (<c>CoreGen.CoreData</c>), and in each
/// rebuilt class (a partial) the methods that fill it from its vanilla data. Fill code lives inside the class, so it
/// assigns private fields directly; values are typed C# for the field they land in, so a renamed or retyped field is a
/// compile error instead of lost data.
/// </summary>
public sealed class Emitter
{
	private const string Rt = "global::CoreGen.";

	private readonly Planner? planner;
	private readonly Model model;
	public readonly List<Diagnostic> Diagnostics = new();

	/// <summary>Generated members per rebuilt class.</summary>
	private readonly Dictionary<INamedTypeSymbol, Code> partials = new(SymbolEqualityComparer.Default);
	private readonly Dictionary<INamedTypeSymbol, Dictionary<string, string>> callHelpers = new(SymbolEqualityComparer.Default);

	/// <summary>State while emitting one scope.</summary>
	private Scope scope = null!;
	private readonly HashSet<ObjId> created = new();
	/// <summary>State while emitting one instance's fill.</summary>
	private RebuiltInstance current = null!;
	private List<string> link = new();

	public Emitter(Planner? planner, Model model)
	{
		this.planner = planner;
		this.model = model;
	}

	private GameFiles Files => planner!.Files;

	private void Error(DiagnosticDescriptor d, Loc? at, params object[] args) => Model.Report(Diagnostics.Add, d, at, args);

	public string Emit()
	{
		foreach (RebuiltType r in model.Rebuilt.Where(r => !r.Invalid))
		{
			Code p = Partial(r.Symbol);
			p.Line("/// <summary>First statement of Awake (or OnEnable): fills the component with the vanilla data CoreGen generated for it.</summary>");
			p.Line($"private void CoreFill() => {Rt}Fixer.Fill(this);");
		}
		Code data = new();
		data.Line("/// <summary>Recreates the components whose vanilla script data Unity skips (run by <see cref=\"Fixer\"/>).</summary>");
		data.Line("internal static class CoreData");
		data.Open();
		List<Scope> scopes = planner == null ? new() : planner.Scopes.Where(s => s.Instances.Count + s.Incoming.Count + s.IncomingCalls.Count > 0).OrderBy(s => s.PrefabRoot == null).ThenBy(s => s.File.BuildIndex).ThenBy(s => s.ResourcePath, StringComparer.Ordinal).ToList();
		data.Line("/// <summary>Rebuilds components on Resources prefabs once, so every instance is created whole.</summary>");
		data.Line("public static void FixPrefabs()");
		data.Open();
		foreach (Scope s in scopes.Where(s => s.PrefabRoot != null))
		{
			data.Line($"{s.Method}();");
		}
		data.Close();
		data.Line("");
		data.Line("/// <summary>Rebuilds the components of a scene that has just loaded (after Awake/OnEnable, before Start).</summary>");
		data.Line("public static void FixScene(int buildIndex, Hierarchy s)");
		data.Open();
		data.Line("switch (buildIndex)");
		data.Open();
		foreach (Scope s in scopes.Where(s => s.PrefabRoot == null))
		{
			data.Line($"case {s.File.BuildIndex}:");
			data.Indent++;
			data.Line($"{s.Method}(s);");
			data.Line("break;");
			data.Indent--;
		}
		data.Close();
		data.Close();
		foreach (Scope s in scopes)
		{
			data.Line("");
			EmitScope(s, data);
		}
		data.Close();

		StringBuilder sb = new();
		sb.Append("// <auto-generated>\n// Generated by Tools/CoreGen from the vanilla game files and this project's source. Do not edit.\n// </auto-generated>\n#pragma warning disable\n#nullable disable\n\n");
		if (planner != null && planner.NotInVanilla.Count > 0)
		{
			sb.Append("// Fields the vanilla layout does not have; the build compiles them as [NonSerialized] (CoreGen.targets).\n");
			foreach (IFieldSymbol f in planner.NotInVanilla.OrderBy(f => f.ContainingType.ToDisplayString(), StringComparer.Ordinal).ThenBy(f => f.Name, StringComparer.Ordinal))
			{
				sb.Append($"[assembly: global::CoreGen.NotInVanillaLayout(typeof({TypeName(f.ContainingType)}), {Str(f.Name)})]\n");
			}
			sb.Append('\n');
		}
		sb.Append("namespace CoreGen\n{\n").Append(data.Indented(1)).Append("}\n");
		foreach (KeyValuePair<INamedTypeSymbol, Code> p in partials.OrderBy(p => p.Key.ToDisplayString(), StringComparer.Ordinal))
		{
			sb.Append($"\nnamespace {p.Key.ContainingNamespace.ToDisplayString()}\n{{\n");
			if (planner?.ExecutionOrders.TryGetValue(p.Key, out int order) == true)
			{
				sb.Append($"\t// The vanilla script's execution order (its MonoScript's, which a rebuilt class does not have).\n\t[global::UnityEngine.DefaultExecutionOrder({order})]\n");
			}
			sb.Append($"\tpartial class {p.Key.Name}\n\t{{\n").Append(p.Value.Indented(2)).Append("\t}\n}\n");
		}
		return sb.ToString();
	}

	private Code Partial(INamedTypeSymbol type)
	{
		if (!partials.TryGetValue(type, out Code? code))
		{
			partials[type] = code = new Code();
		}
		else
		{
			code.Line("");
		}
		return code;
	}

	private void EmitScope(Scope s, Code data)
	{
		scope = s;
		created.Clear();
		if (s.PrefabRoot == null)
		{
			data.Line($"// {s.File.Name}");
			data.Line($"private static void {s.Method}(Hierarchy s)");
			data.Open();
		}
		else
		{
			data.Line($"// Prefab '{s.PrefabRoot.Name}' (Resources/{s.ResourcePath}) in {s.File.Name}");
			data.Line($"private static void {s.Method}()");
			data.Open();
			data.Line($"Hierarchy s = Hierarchy.Prefab({Str(s.ResourcePath!)});");
		}
		List<string> links = new();
		List<RebuiltInstance> order = CreationOrder(s.Instances);
		for (int i = 0; i < order.Count; i++)
		{
			RebuiltInstance inst = order[i];
			try
			{
				string go = GoExpr(Files.Get(inst.Obj.GameObject!.Value)!);
				bool hasLink = EmitInstance(inst);
				string type = TypeName(inst.Script.Type!);
				data.Line($"// {inst.Script.Vanilla.Info.FullName} on '{Files.Get(inst.Obj.GameObject!.Value)!.Name}' ({inst.Obj.Id})");
				data.Line($"var c{i} = Fixer.Rebuild<{type}>({go}, c => {type}.__CoreFill_{inst.Id}(c, s));");
				if (hasLink)
				{
					links.Add($"{type}.__CoreLink_{inst.Id}(c{i}, s);");
				}
			}
			catch (CoreGenException e)
			{
				Error(Descriptors.Generation, Loc.Of(inst.Script.Type), inst.Obj.ToString(), e.Message);
			}
			created.Add(inst.Obj.Id);
		}
		if (links.Count > 0)
		{
			data.Line("// References to rebuilt components created later, and UnityEvent calls held by rebuilt components");
			foreach (string l in links)
			{
				data.Line(l);
			}
		}
		if (s.Incoming.Count + s.IncomingCalls.Count > 0)
		{
			data.Line("// References and UnityEvent calls that loaded components held to rebuilt ones");
			foreach (RefInfo r in s.Incoming)
			{
				Guard(r.Owner, () => data.Line($"Links.Set({ObjectExpr(r.Owner, null)}, {Str(planner!.OwnerPath(r.Owner, r.Path))}, {ObjectExpr(r.Target, null)});"));
			}
			foreach (CallInfo c in s.IncomingCalls)
			{
				Guard(c.Owner, () => data.Line($"Links.Listen({ObjectExpr(c.Owner, null)}, {Str(planner!.OwnerPath(c.Owner, c.EventPath))}, {CallDelegate(c, null)});"));
			}
		}
		data.Close();
	}

	private void Guard(GameObj owner, Action emit)
	{
		try
		{
			emit();
		}
		catch (CoreGenException e)
		{
			Error(Descriptors.Generation, null, owner.ToString(), e.Message);
		}
	}

	/// <summary>Writes the fill (and if needed link) method into the rebuilt class; true if it has a link method.</summary>
	private bool EmitInstance(RebuiltInstance inst)
	{
		current = inst;
		link = new List<string>();
		INamedTypeSymbol target = inst.Script.Type!;
		List<string> body = new();
		List<string> dropped = new();
		AssetTypeValueField data = inst.Obj.Data!;
		foreach (AssetTypeValueField field in data.Children.Skip(4))
		{
			string name = field.TemplateField.Name;
			string? memberPath = inst.Script.Rebuilt!.FieldMap.TryGetValue(name, out string? mapped) ? mapped : Model.FindField(target, name) != null ? name : null;
			if (string.IsNullOrEmpty(memberPath))
			{
				dropped.Add($"{name} = {Summary(field)}");
				continue;
			}
			(ITypeSymbol type, bool direct) = ResolveMember(target, memberPath!);
			string lvalue = "c." + memberPath;
			string? value = Convert(field, type, lvalue);
			if (value != null)
			{
				body.Add(direct ? $"{lvalue} = {value};" : $"{Rt}Links.Set(c, {Str(memberPath!)}, {value});");
			}
		}
		if (data["m_Enabled"].AsByte == 0)
		{
			body.Add("c.enabled = false;");
		}
		GameObj go = Files.Get(inst.Obj.GameObject!.Value)!;
		Code p = Partial(target);
		p.Line($"// {inst.Script.Vanilla.Info.FullName} on '{go.Name}' ({inst.Obj.Id}{(scope.PrefabRoot != null ? ", prefab Resources/" + scope.ResourcePath : "")})");
		if (dropped.Count > 0)
		{
			p.Line("// Vanilla state with no field here (dropped): " + string.Join(", ", dropped));
		}
		p.Line($"internal static void __CoreFill_{inst.Id}({target.Name} c, {Rt}Hierarchy s)");
		p.Open();
		foreach (string b in body)
		{
			p.Line(b);
		}
		p.Close();
		if (link.Count == 0)
		{
			return false;
		}
		p.Line($"internal static void __CoreLink_{inst.Id}({target.Name} c, {Rt}Hierarchy s)");
		p.Open();
		foreach (string l in link)
		{
			p.Line(l);
		}
		p.Close();
		return true;
	}

	/// <summary>Instances that others in the scope reference come first, so fills see them; cycles fall back to link methods.</summary>
	private List<RebuiltInstance> CreationOrder(List<RebuiltInstance> instances)
	{
		Dictionary<ObjId, HashSet<ObjId>> deps = new();
		foreach (RebuiltInstance i in instances)
		{
			HashSet<ObjId> d = new();
			CollectRefs(i.Obj.Data!, i.Obj.File, d);
			d.RemoveWhere(x => x == i.Obj.Id || !planner!.Rebuilt.TryGetValue(x, out RebuiltInstance? t) || t.Scope != i.Scope);
			deps[i.Obj.Id] = d;
		}
		List<RebuiltInstance> result = new();
		HashSet<ObjId> done = new();
		List<RebuiltInstance> pending = instances.OrderBy(i => i.Obj.File.Name, StringComparer.Ordinal).ThenBy(i => i.Obj.Id.PathId).ToList();
		while (pending.Count > 0)
		{
			RebuiltInstance next = pending.FirstOrDefault(i => deps[i.Obj.Id].All(done.Contains)) ?? pending[0];
			result.Add(next);
			done.Add(next.Obj.Id);
			pending.Remove(next);
		}
		return result;
	}

	private void CollectRefs(AssetTypeValueField f, GameFile file, HashSet<ObjId> into)
	{
		if (f.TemplateField.Type.StartsWith("PPtr<"))
		{
			if (Files.Get(file, f) is { } o)
			{
				into.Add(o.Id);
			}
			return;
		}
		foreach (AssetTypeValueField c in f.Children ?? new List<AssetTypeValueField>())
		{
			CollectRefs(c, file, into);
		}
	}

