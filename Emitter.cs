	/// <summary>C# for a vanilla value as the given type; null when it is assigned later in the link method.</summary>
	private string? Convert(AssetTypeValueField v, ITypeSymbol type, string lvalue)
	{
		if (Model.Element(type) is { } elem)
		{
			List<AssetTypeValueField> items = Elements(v, type);
			List<string> parts = new();
			for (int i = 0; i < items.Count; i++)
			{
				parts.Add(Convert(items[i], elem, $"{lvalue}[{i}]") ?? "null");
			}
			return type is IArrayTypeSymbol ? $"new {TypeName(elem)}[] {{ {string.Join(", ", parts)} }}" : $"new {TypeName(type)} {{ {string.Join(", ", parts)} }}";
		}
		if (type.TypeKind == TypeKind.Enum)
		{
			return $"({TypeName(type)})({Integer(v)})";
		}
		switch (type.SpecialType)
		{
		case SpecialType.System_Boolean:
			return v.AsBool ? "true" : "false";
		case SpecialType.System_Single:
			return Float(v.AsFloat);
		case SpecialType.System_Double:
			return v.AsDouble.ToString("R", CultureInfo.InvariantCulture) + "d";
		case SpecialType.System_String:
			return Str(v.AsString);
		case SpecialType.System_Byte or SpecialType.System_SByte or SpecialType.System_Int16 or SpecialType.System_UInt16 or SpecialType.System_Int32 or SpecialType.System_UInt32 or SpecialType.System_Int64 or SpecialType.System_UInt64 or SpecialType.System_Char:
			return $"({TypeName(type)})({Integer(v)})";
		}
		if (Model.IsUnityObject(type))
		{
			return Reference(v, lvalue);
		}
		if (Model.Inherits(type, "UnityEngine.Events.UnityEventBase"))
		{
			return UnityEvent(v, type, lvalue);
		}
		if (SpecialUnity(v, Model.FullName(type)) is { } special)
		{
			return special;
		}
		if (type is INamedTypeSymbol { IsSerializable: true } named)
		{
			INamedTypeSymbol rebuilt = current.Script.Type!;
			List<string> inits = new();
			foreach (AssetTypeValueField child in v.Children)
			{
				string n = child.TemplateField.Name;
				IFieldSymbol? f = Model.FindField(named, n);
				if (f == null || f.IsReadOnly || !model.Accessible(f, rebuilt))
				{
					throw new CoreGenException($"{lvalue}: {named.ToDisplayString()} has no field '{n}' that {rebuilt.Name} can set (vanilla {Summary(child)}); make it accessible, or drop {lvalue} with a field map");
				}
				string? cv = Convert(child, f.Type, $"{lvalue}.{n}");
				if (cv != null)
				{
					inits.Add($"{n} = {cv}");
				}
			}
			return $"new {TypeName(type)} {{ {string.Join(", ", inits)} }}";
		}
		throw new CoreGenException($"{lvalue}: cannot emit a value of type {type.ToDisplayString()}");
	}

	private static List<AssetTypeValueField> Elements(AssetTypeValueField v, ITypeSymbol type)
	{
		AssetTypeValueField array = v.TemplateField.IsArray ? v : v.Children?.FirstOrDefault(c => c.TemplateField.IsArray) ?? throw new CoreGenException($"vanilla value {v.TemplateField.Name} is not an array but maps to {type.ToDisplayString()}");
		return array.Children;
	}

	/// <summary>A new, empty event whose persistent calls are re-added as listeners once the scope is built.</summary>
	private string UnityEvent(AssetTypeValueField v, ITypeSymbol type, string lvalue)
	{
		AssetTypeValueField calls = v["m_PersistentCalls"]["m_Calls"];
		foreach (AssetTypeValueField call in Elements(calls, type))
		{
			GameObj? target = Files.Get(current.Obj.File, call["m_Target"]);
			if (target == null)
			{
				continue; // an unset call does nothing in vanilla either
			}
			AssetTypeValueField args = call["m_Arguments"];
			CallInfo info = new()
			{
				Owner = current.Obj,
				Target = target,
				Method = call["m_MethodName"].AsString,
				Mode = call["m_Mode"].AsInt,
				ObjectArgument = Files.Get(current.Obj.File, args["m_ObjectArgument"]),
				IntArgument = args["m_IntArgument"].AsInt,
				FloatArgument = args["m_FloatArgument"].AsFloat,
				StringArgument = args["m_StringArgument"].AsString,
				BoolArgument = args["m_BoolArgument"].AsBool,
			};
			link.Add($"{Rt}Links.Listen(c, {Str(lvalue.Substring(2))}, {CallDelegate(info, current.Script.Type)});");
		}
		return $"new {TypeName(type)}()";
	}

	/// <summary>
	/// A delegate that makes a UnityEvent persistent call. On a rebuilt target it comes from a helper in the target's
	/// class (its method may be private); on others the method must be accessible from where the code runs.
	/// </summary>
	private string CallDelegate(CallInfo call, INamedTypeSymbol? from)
	{
		ITypeSymbol targetType = ObjectType(call.Target);
		IMethodSymbol method = Planner.FindCallMethod(targetType, call) ?? throw new CoreGenException($"UnityEvent call to {targetType.ToDisplayString()}.{call.Method} {Planner.ModeDescription(call.Mode)}: no such method");
		string targetExpr = ObjectExpr(call.Target, null);
		string arg = call.ObjectArgument == null ? "null" : ObjectExpr(call.ObjectArgument, null);
		if (planner!.Rebuilt.ContainsKey(call.Target.Id) && targetType is INamedTypeSymbol rebuilt)
		{
			return $"{TypeName(rebuilt)}.{CallHelper(rebuilt, method, call)}({targetExpr}, {arg})";
		}
		if (!(from == null ? model.Compilation.IsSymbolAccessibleWithin(method, model.Compilation.Assembly) : model.Accessible(method, from)))
		{
			throw new CoreGenException($"UnityEvent call to {targetType.ToDisplayString()}.{call.Method}: the method is not accessible from the generated code; make it internal or public");
		}
		return Lambda(method, call, method.IsStatic ? TypeName(targetType) : $"(({TypeName(targetType)}){targetExpr})", arg);
	}

	private string CallHelper(INamedTypeSymbol type, IMethodSymbol method, CallInfo call)
	{
		string body = Lambda(method, call, method.IsStatic ? type.Name : "c", "a");
		if (!callHelpers.TryGetValue(type, out Dictionary<string, string>? helpers))
		{
			callHelpers[type] = helpers = new Dictionary<string, string>();
		}
		if (!helpers.TryGetValue(body, out string? name))
		{
			helpers[body] = name = $"__CoreCall_{Identifier(method.Name)}_{helpers.Count}";
			Code p = Partial(type);
			p.Line($"internal static global::System.Delegate {name}({type.Name} c, global::UnityEngine.Object a) => {body};");
		}
		return name;
	}

	/// <summary>The call as a typed UnityAction: static arguments are constants, the object argument comes in as <paramref name="arg"/>.</summary>
	private string Lambda(IMethodSymbol m, CallInfo call, string receiver, string arg)
	{
		string invoke = $"{receiver}.{m.Name}";
		if (m.MethodKind == MethodKind.PropertySet)
		{
			string property = m.AssociatedSymbol!.Name;
			return call.Mode == 0
				? $"(global::UnityEngine.Events.UnityAction<{TypeName(m.Parameters[0].Type)}>)(p0 => {receiver}.{property} = p0)"
				: $"(global::UnityEngine.Events.UnityAction)(() => {receiver}.{property} = {StaticArgument(m, call, arg)})";
		}
		if (call.Mode == 0)
		{
			string types = string.Join(", ", m.Parameters.Select(p => TypeName(p.Type)));
			string names = string.Join(", ", m.Parameters.Select((_, i) => "p" + i));
			string action = m.Parameters.Length == 0 ? "global::UnityEngine.Events.UnityAction" : $"global::UnityEngine.Events.UnityAction<{types}>";
			return $"({action})(({names}) => {invoke}({names}))";
		}
		return $"(global::UnityEngine.Events.UnityAction)(() => {invoke}({(call.Mode == 1 ? "" : StaticArgument(m, call, arg))}))";
	}

	private static string StaticArgument(IMethodSymbol m, CallInfo call, string arg) => call.Mode switch
	{
		2 => $"({TypeName(m.Parameters[0].Type)}){arg}",
		3 => call.IntArgument.ToString(CultureInfo.InvariantCulture),
		4 => Float(call.FloatArgument),
		5 => Str(call.StringArgument),
		6 => call.BoolArgument ? "true" : "false",
		_ => "",
	};

	private static string Integer(AssetTypeValueField v) => v.Value.ValueType switch
	{
		AssetValueType.Int64 => v.AsLong.ToString(CultureInfo.InvariantCulture),
		AssetValueType.UInt64 => v.AsULong.ToString(CultureInfo.InvariantCulture),
		AssetValueType.UInt32 => v.AsUInt.ToString(CultureInfo.InvariantCulture),
		AssetValueType.Bool => v.AsBool ? "1" : "0",
		_ => v.AsInt.ToString(CultureInfo.InvariantCulture),
	};

	public static string Float(float f)
	{
		if (float.IsNaN(f))
		{
			return "float.NaN";
		}
		if (float.IsPositiveInfinity(f))
		{
			return "float.PositiveInfinity";
		}
		if (float.IsNegativeInfinity(f))
		{
			return "float.NegativeInfinity";
		}
		return f.ToString("R", CultureInfo.InvariantCulture) + "f";
	}

	public static string Str(string s)
	{
		StringBuilder b = new("\"");
		foreach (char c in s)
		{
			b.Append(c switch
			{
				'"' => "\\\"",
				'\\' => "\\\\",
				'\n' => "\\n",
				'\r' => "\\r",
				'\t' => "\\t",
				_ when c < 32 => $"\\u{(int)c:x4}",
				_ => c.ToString(),
			});
		}
		return b.Append('"').ToString();
	}

	private static string F(AssetTypeValueField v, string name) => Float(v[name].AsFloat);

	private static string? SpecialUnity(AssetTypeValueField v, string fullName) => fullName switch
	{
		"UnityEngine.Vector2" => $"new global::UnityEngine.Vector2({F(v, "x")}, {F(v, "y")})",
		"UnityEngine.Vector3" => $"new global::UnityEngine.Vector3({F(v, "x")}, {F(v, "y")}, {F(v, "z")})",
		"UnityEngine.Vector4" => $"new global::UnityEngine.Vector4({F(v, "x")}, {F(v, "y")}, {F(v, "z")}, {F(v, "w")})",
		"UnityEngine.Quaternion" => $"new global::UnityEngine.Quaternion({F(v, "x")}, {F(v, "y")}, {F(v, "z")}, {F(v, "w")})",
		"UnityEngine.Vector2Int" => $"new global::UnityEngine.Vector2Int({v["m_X"].AsInt}, {v["m_Y"].AsInt})",
		"UnityEngine.Vector3Int" => $"new global::UnityEngine.Vector3Int({v["m_X"].AsInt}, {v["m_Y"].AsInt}, {v["m_Z"].AsInt})",
		"UnityEngine.Color" => $"new global::UnityEngine.Color({F(v, "r")}, {F(v, "g")}, {F(v, "b")}, {F(v, "a")})",
		"UnityEngine.Color32" => Color32(v),
		"UnityEngine.Rect" => $"new global::UnityEngine.Rect({F(v, "x")}, {F(v, "y")}, {F(v, "width")}, {F(v, "height")})",
		"UnityEngine.Bounds" => $"new global::UnityEngine.Bounds({SpecialUnity(v["m_Center"], "UnityEngine.Vector3")}, 2f * {SpecialUnity(v["m_Extent"], "UnityEngine.Vector3")})",
		"UnityEngine.LayerMask" => $"new global::UnityEngine.LayerMask {{ value = {(int)v["m_Bits"].AsUInt} }}",
		"UnityEngine.AnimationCurve" => Curve(v),
		"UnityEngine.Gradient" => Gradient(v),
		_ => null,
	};

	private static string Color32(AssetTypeValueField v)
	{
		uint rgba = v["rgba"].AsUInt;
		return $"new global::UnityEngine.Color32({rgba & 0xff}, {(rgba >> 8) & 0xff}, {(rgba >> 16) & 0xff}, {rgba >> 24})";
	}

	private static string Curve(AssetTypeValueField v)
	{
		List<string> keys = new();
		foreach (AssetTypeValueField k in v["m_Curve"].Children[0].Children)
		{
			string weighted = k["weightedMode"].AsInt != 0 ? $" {{ weightedMode = (global::UnityEngine.WeightedMode){k["weightedMode"].AsInt} }}" : "";
			keys.Add($"new global::UnityEngine.Keyframe({F(k, "time")}, {F(k, "value")}, {F(k, "inSlope")}, {F(k, "outSlope")}, {F(k, "inWeight")}, {F(k, "outWeight")}){weighted}");
		}
		return $"new global::UnityEngine.AnimationCurve({string.Join(", ", keys)}) {{ preWrapMode = {WrapMode(v["m_PreInfinity"].AsInt)}, postWrapMode = {WrapMode(v["m_PostInfinity"].AsInt)} }}";
	}

	/// <summary>
	/// A curve's serialized m_PreInfinity/m_PostInfinity is Unity's internal wrap mode (0 ping-pong, 1 repeat, 2 clamp —
	/// what every default curve has), not the WrapMode enum: cast as is, clamp (2) became WrapMode.Loop (2) and curves
	/// wrapped back to their start at their last key.
	/// </summary>
	private static string WrapMode(int internalMode) => internalMode switch
	{
		0 => "global::UnityEngine.WrapMode.PingPong",
		1 => "global::UnityEngine.WrapMode.Loop",
		2 => "global::UnityEngine.WrapMode.ClampForever",
		_ => "global::UnityEngine.WrapMode.Default",
	};

	private static string Gradient(AssetTypeValueField v)
	{
		int colors = v["m_NumColorKeys"].AsInt, alphas = v["m_NumAlphaKeys"].AsInt;
		List<string> c = new(), a = new();
		for (int i = 0; i < colors; i++)
		{
			AssetTypeValueField k = v["key" + i];
			c.Add($"new global::UnityEngine.GradientColorKey(new global::UnityEngine.Color({F(k, "r")}, {F(k, "g")}, {F(k, "b")}), {Float(v["ctime" + i].AsInt / 65535f)})");
		}
		for (int i = 0; i < alphas; i++)
		{
			a.Add($"new global::UnityEngine.GradientAlphaKey({F(v["key" + i], "a")}, {Float(v["atime" + i].AsInt / 65535f)})");
		}
		AssetTypeValueField? space = v.Children.FirstOrDefault(x => x.TemplateField.Name == "m_ColorSpace");
		string colorSpace = space is { AsInt: >= 0 } ? $"colorSpace = (global::UnityEngine.ColorSpace){space.AsInt}, " : ""; // -1: not set

		return $"new global::UnityEngine.Gradient {{ mode = (global::UnityEngine.GradientMode){v["m_Mode"].AsInt}, {colorSpace}colorKeys = new global::UnityEngine.GradientColorKey[] {{ {string.Join(", ", c)} }}, alphaKeys = new global::UnityEngine.GradientAlphaKey[] {{ {string.Join(", ", a)} }} }}";
	}

	private static string Summary(AssetTypeValueField v)
	{
		if (v.TemplateField.Type.StartsWith("PPtr<"))
		{
			return v["m_PathID"].AsLong == 0 ? "null" : "ref";
		}
		if (v.Value != null && v.TemplateField.HasValue && !v.TemplateField.IsArray)
		{
			return v.Value.ValueType switch
			{
				AssetValueType.String => Str(v.AsString),
				AssetValueType.Float => Float(v.AsFloat),
				AssetValueType.Bool => v.AsBool ? "true" : "false",
				_ => Integer(v),
			};
		}
		AssetTypeValueField? array = v.TemplateField.IsArray ? v : v.Children?.FirstOrDefault(c => c.TemplateField.IsArray);
		return array != null ? $"[{array.Children.Count}]" : "{...}";
	}

